-- ============================================================================
-- gge-storm-dungeons - schema base (HIS1)
-- ============================================================================

create table if not exists public.alliances (
  id bigint primary key,
  name text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.players (
  id bigint primary key,
  name text not null,
  alliance_id bigint,
  might_current bigint not null default 0,
  might_all_time bigint not null default 0,
  loot_current bigint not null default 0,
  loot_all_time bigint not null default 0,
  level smallint,
  legendary_level smallint,
  current_fame numeric(20, 0) not null default 0,
  highest_fame numeric(20, 0) not null default 0,
  honor integer not null default 0,
  max_honor integer not null default 0,
  castles jsonb,
  peace_disabled_at timestamptz,
  is_ruin boolean not null default false,
  updated_at timestamptz not null default now()
);

create index if not exists players_name_lower_idx on public.players (lower(name) text_pattern_ops);
create index if not exists players_alliance_idx on public.players (alliance_id);

create table if not exists public.storm_meta (
  id boolean primary key default true,
  season_started_at timestamptz,
  season_checked_at timestamptz,
  scan_radius smallint,
  last_scan_at timestamptz,
  own_isle_object_id integer,
  own_isle_x smallint,
  own_isle_y smallint,
  constraint storm_meta_single_row check (id = true)
);

create table if not exists public.storm_forts (
  kid smallint not null default 4,
  position_x smallint not null,
  position_y smallint not null,
  isle_id smallint not null,
  victory_count smallint not null default 0,
  is_visible boolean not null default true,
  available_at timestamptz not null default now(),
  available_since_observed boolean not null default false,
  last_available_seconds integer,
  updated_at timestamptz not null default now(),
  primary key (kid, position_x, position_y)
);

create index if not exists storm_forts_available_idx on public.storm_forts (available_at);
create index if not exists storm_forts_isle_idx on public.storm_forts (isle_id);

create table if not exists public.storm_isles (
  kid smallint not null default 4,
  position_x smallint not null,
  position_y smallint not null,
  object_id integer not null,
  isle_id smallint not null,
  occupier_id bigint,
  state smallint not null default 0,
  available_at timestamptz not null default now(),
  available_since_observed boolean not null default false,
  last_available_seconds integer,
  updated_at timestamptz not null default now(),
  primary key (kid, position_x, position_y)
);

create index if not exists storm_isles_state_idx on public.storm_isles (state);
create index if not exists storm_isles_occupier_idx on public.storm_isles (occupier_id);

create table if not exists public.dungeons (
  kid smallint not null,
  position_x smallint not null,
  position_y smallint not null,
  player_id bigint,
  attack_count integer not null default 0,
  last_attack_at timestamptz,
  previous_attack_at timestamptz,
  last_attacker_id bigint,
  global_available_at timestamptz not null default now(),
  player_available_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (kid, position_x, position_y)
);

create index if not exists dungeons_cooldown_idx on public.dungeons (global_available_at);
create index if not exists dungeons_attacker_idx on public.dungeons (last_attacker_id);

create table if not exists public.dungeons_history (
  id bigint generated by default as identity primary key,
  kid smallint not null,
  position_x smallint not null,
  position_y smallint not null,
  player_id bigint,
  attacked_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists dungeons_history_player_idx on public.dungeons_history (player_id, attacked_at desc);
create index if not exists dungeons_history_attacked_idx on public.dungeons_history (attacked_at);

create table if not exists public.scrape_runs (
  id bigint generated by default as identity primary key,
  job text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  ok boolean,
  rows integer,
  error text
);

insert into public.storm_meta (id) values (true) on conflict (id) do nothing;

-- ============================================================================
-- Vistas de lectura (lo que consume el frontend)
-- ============================================================================

create or replace view public.v_storm_forts as
select
  f.kid,
  f.position_x,
  f.position_y,
  f.isle_id,
  f.victory_count,
  greatest(10 - f.victory_count, 0) as attacks_left,
  f.is_visible,
  f.available_at,
  f.available_since_observed,
  f.last_available_seconds,
  f.updated_at
from public.storm_forts f;

create or replace view public.v_storm_isles as
select
  i.kid,
  i.position_x,
  i.position_y,
  i.object_id,
  i.isle_id,
  i.state,
  i.occupier_id,
  p.name as occupier_name,
  p.might_current as occupier_might,
  p.level as occupier_level,
  p.legendary_level as occupier_legendary_level,
  a.name as occupier_alliance_name,
  i.available_at,
  i.available_since_observed,
  i.last_available_seconds,
  i.updated_at
from public.storm_isles i
left join public.players p on p.id = i.occupier_id
left join public.alliances a on a.id = p.alliance_id;

create or replace view public.v_storm_meta as
select
  m.season_started_at,
  coalesce(m.scan_radius, 0) as scan_radius,
  m.last_scan_at,
  (select count(*) from public.storm_forts) as forts_count,
  (select count(*) from public.storm_isles) as isles_count
from public.storm_meta m;

create or replace view public.v_dungeons as
select
  d.kid,
  d.position_x,
  d.position_y,
  d.last_attacker_id as player_id,
  p.name as player_name,
  p.might_current as player_might,
  p.level as player_level,
  p.legendary_level as player_legendary_level,
  d.attack_count as total_attack_count,
  d.last_attack_at as last_attack,
  d.previous_attack_at,
  d.global_available_at,
  d.global_available_at as effective_cooldown_until,
  d.updated_at
from public.dungeons d
left join public.players p on p.id = d.last_attacker_id;

create or replace view public.v_dungeons_history as
select
  kid,
  position_x,
  position_y,
  player_id,
  attacked_at
from public.dungeons_history;

create or replace view public.v_players as
select
  p.id,
  p.name,
  p.alliance_id,
  a.name as alliance_name,
  p.might_current,
  p.level,
  p.legendary_level,
  p.current_fame,
  p.honor,
  p.castles
from public.players p
left join public.alliances a on a.id = p.alliance_id;

